Console.WriteLine("Digite um numero inteiro: ");
int x = int.Parse(Console.ReadLine());
Console.WriteLine("Digite outro numero inteiro: ");
int y = int.Parse(Console.ReadLine());
Console.WriteLine(x + " + " + y + " = " + (x + y));
Console.WriteLine(x + " - " + y + " = " + (x - y));
Console.WriteLine(x + " * " + y + " = " + (x * y));
Console.WriteLine(x + " / " + y + " = " + (x / y));

